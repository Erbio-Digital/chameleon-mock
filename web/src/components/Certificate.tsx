import { useState } from 'react'
import { useMutation } from '@tanstack/react-query'
import { Copy, Eye, EyeOff } from 'lucide-react'
import { api, type Connector, type SubscriptionCertificate } from '@/api'
import { copyText, download, ErrorText, save } from '@/components/common'
import { dayTime } from '@/format'

/**
 * Client certificate of the sandbox as a first-time walkthrough: get the .pfx (the
 * password is asked on the first download and kept sealed), configure the service, trust the CA.
 * PEM files and the app's own CSR stay under "Other formats".
 */
export function Certificate({ sandbox, c, cert, onDone }: { sandbox: string; c: Connector; cert: SubscriptionCertificate; onDone: (msg: string) => void }) {
  const [csr, setCsr] = useState<string | null>(null)
  const [asking, setAsking] = useState<{ password: string; confirm: string } | null>(null)
  const [showPassword, setShowPassword] = useState(false)
  const sign = useMutation({
    mutationFn: (text: string) => api.signCsr(sandbox, c.name, text),
    onSuccess: () => {
      setCsr(null)
      onDone('Certificate signed from the CSR. The previous one is no longer valid.')
    },
  })
  const pfx = useMutation({
    mutationFn: async (password?: string) => {
      if (password) await api.setPfxPassword(sandbox, c.name, password)
      save(`${prefix}.pfx`, await api.pfx(sandbox, c.name))
    },
    onSuccess: (_, password) => {
      setAsking(null)
      onDone(password ? '.pfx password saved and file downloaded.' : '.pfx downloaded.')
    },
  })
  const prefix = `${c.name}-${sandbox}`
  const generated = !!cert.keyPem
  const mismatch = !!asking && asking.confirm !== '' && asking.password !== asking.confirm

  return (
    <div className="col" style={{ padding: '4px 14px 10px', gap: 14 }}>
      <div className="row" style={{ gap: 8, flexWrap: 'wrap', alignItems: 'baseline' }}>
        <b className="small">Client certificate (mTLS)</b>
        <span className="small muted">
          {cert.source === 'Csr' ? 'signed from the application CSR' : 'generated by Chameleon'} · valid until {dayTime(cert.notAfter)}
        </span>
      </div>
      <span className="small muted">
        Your service presents this certificate on every call to <span className="mono">{sandbox}</span>; without it, the connection is refused.
      </span>

      <div className="row" style={{ gap: 10, alignItems: 'flex-start' }}>
        <span className="step">1</span>
        <div className="col grow" style={{ gap: 8 }}>
          <b className="small">Download the certificate</b>
          {generated ? (
            <>
              <span className="small muted">
                A .pfx file with the certificate and private key, protected by a password.
                {cert.pfxPassword ? '' : ' The first time you set the password; it is stored encrypted here.'}
              </span>
              {asking ? (
                <form
                  className="col"
                  style={{ gap: 8, maxWidth: 360 }}
                  onSubmit={e => {
                    e.preventDefault()
                    if (!mismatch) pfx.mutate(asking.password)
                  }}
                >
                  <label className="col" style={{ gap: 4 }}>
                    <span className="small">.pfx password (at least 8 characters)</span>
                    <input
                      className="field mono"
                      type="password"
                      autoComplete="new-password"
                      required
                      minLength={8}
                      autoFocus
                      value={asking.password}
                      onChange={e => setAsking({ ...asking, password: e.target.value })}
                    />
                  </label>
                  <label className="col" style={{ gap: 4 }}>
                    <span className="small">Confirm the password</span>
                    <input
                      className="field mono"
                      type="password"
                      autoComplete="new-password"
                      required
                      value={asking.confirm}
                      onChange={e => setAsking({ ...asking, confirm: e.target.value })}
                    />
                  </label>
                  {mismatch && <span className="err">The passwords do not match.</span>}
                  <ErrorText error={pfx.error} />
                  <div className="row" style={{ gap: 8 }}>
                    <button className="btn btn-pri" disabled={pfx.isPending || mismatch}>
                      Save and download .pfx
                    </button>
                    <button type="button" className="btn btn-sec" onClick={() => setAsking(null)}>
                      Cancel
                    </button>
                  </div>
                </form>
              ) : (
                <>
                  <div className="row" style={{ gap: 8, flexWrap: 'wrap' }}>
                    <button
                      className="btn btn-pri"
                      disabled={pfx.isPending}
                      onClick={() => (cert.pfxPassword ? pfx.mutate(undefined) : setAsking({ password: '', confirm: '' }))}
                    >
                      Download .pfx
                    </button>
                    {cert.pfxPassword && (
                      <button className="btn btn-sec" onClick={() => setAsking({ password: '', confirm: '' })}>
                        Change password
                      </button>
                    )}
                  </div>
                  {cert.pfxPassword && (
                    <div className="row small" style={{ gap: 6 }}>
                      <span className="muted">.pfx password</span>
                      <span className="mono">{showPassword ? cert.pfxPassword : '•'.repeat(12)}</span>
                      <button
                        className="iconbtn"
                        aria-label={showPassword ? 'Hide .pfx password' : 'Show .pfx password'}
                        onClick={() => setShowPassword(!showPassword)}
                      >
                        {showPassword ? <EyeOff size={14} aria-hidden /> : <Eye size={14} aria-hidden />}
                      </button>
                      <button
                        className="iconbtn"
                        aria-label="Copy .pfx password"
                        onClick={async () => onDone((await copyText(cert.pfxPassword!)) ? '.pfx password copied.' : 'Could not copy.')}
                      >
                        <Copy size={14} aria-hidden />
                      </button>
                    </div>
                  )}
                  <ErrorText error={pfx.error} />
                </>
              )}
            </>
          ) : (
            <>
              <span className="small muted">
                Signed from the CSR: the private key stayed with the application. Combine this .crt with it to build the .pfx on your side.
              </span>
              <div>
                <button className="btn btn-pri" onClick={() => download(`${prefix}.crt`, cert.pem)}>
                  Download .crt
                </button>
              </div>
            </>
          )}
        </div>
      </div>

      <div className="row" style={{ gap: 10, alignItems: 'flex-start' }}>
        <span className="step">2</span>
        <div className="col grow" style={{ gap: 4 }}>
          <b className="small">Configure your service</b>
          <span className="small muted" style={{ lineHeight: 1.55 }}>
            Put the .pfx where your service reads the real provider's certificate, and the password where it reads the certificate password. In .NET, load it with{' '}
            <span className="mono">new X509Certificate2(bytes, password)</span> and add it to <span className="mono">HttpClientHandler.ClientCertificates</span>. If the
            service caches the certificate, clear the cache after replacing it.
          </span>
        </div>
      </div>

      <div className="row" style={{ gap: 10, alignItems: 'flex-start' }}>
        <span className="step">3</span>
        <div className="col grow" style={{ gap: 8 }}>
          <b className="small">Trust the Chameleon CA (local only)</b>
          <span className="small muted" style={{ lineHeight: 1.55 }}>
            The local mTLS port uses a certificate issued by the Chameleon CA. Install the CA as a trusted root on the machine or in the service container; without it, the
            call fails at TLS before reaching Chameleon. Behind a publicly trusted certificate this step is not needed.
          </span>
          <div>
            <button className="btn btn-sec" onClick={() => download('chameleon-ca.crt', cert.caPem)}>
              Download Chameleon CA
            </button>
          </div>
        </div>
      </div>

      <details>
        <summary className="small" style={{ cursor: 'pointer' }}>
          Other formats (PEM and application CSR)
        </summary>
        <div className="col" style={{ gap: 8, marginTop: 8 }}>
          <span className="small muted">For stacks that read PEM (Node, Python, nginx, openssl) or to sign the key the application generated itself.</span>
          <div className="row" style={{ gap: 8, flexWrap: 'wrap' }}>
            <button className="btn btn-sec" onClick={() => download(`${prefix}.crt`, cert.pem)}>
              Download .crt
            </button>
            {cert.keyPem && (
              <button className="btn btn-sec" onClick={() => download(`${prefix}.key`, cert.keyPem!)}>
                Download .key
              </button>
            )}
            {csr === null && (
              <button className="btn btn-sec" onClick={() => setCsr('')}>
                Use the application CSR
              </button>
            )}
          </div>
          {csr !== null && (
            <form
              className="col"
              style={{ gap: 6 }}
              onSubmit={e => {
                e.preventDefault()
                sign.mutate(csr)
              }}
            >
              <label className="col" style={{ gap: 4 }}>
                <span className="small">CSR in PEM (the private key stays with the application)</span>
                <textarea
                  className="field mono"
                  rows={5}
                  required
                  placeholder="-----BEGIN CERTIFICATE REQUEST-----"
                  value={csr}
                  onChange={e => setCsr(e.target.value)}
                />
              </label>
              <ErrorText error={sign.error} />
              <div className="row" style={{ gap: 8 }}>
                <button className="btn btn-pri" disabled={sign.isPending}>
                  Sign
                </button>
                <button type="button" className="btn btn-sec" onClick={() => setCsr(null)}>
                  Cancel
                </button>
              </div>
            </form>
          )}
        </div>
      </details>
    </div>
  )
}
