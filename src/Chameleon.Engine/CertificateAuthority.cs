using System.Collections.Concurrent;
using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;

namespace Chameleon.Engine;

/// The Chameleon certificate authority: signs the client certificates issued per
/// sandbox (or the app's own CSR), the local mTLS server certificate and each connector's webhook
/// certificate. Stable across restarts and instances because it comes from the environment.
public sealed class CertificateAuthority
{
    public const string CertVariable = "CHAMELEON_CA_CERT";
    public const string KeyVariable = "CHAMELEON_CA_KEY";

    private static readonly Oid ClientAuth = new("1.3.6.1.5.5.7.3.2");
    private static readonly Oid ServerAuth = new("1.3.6.1.5.5.7.3.1");
    private static readonly TimeSpan ClientValidity = TimeSpan.FromDays(365);

    private readonly X509Certificate2 _ca;
    private readonly ConcurrentDictionary<string, X509Certificate2> _webhook = new();

    public CertificateAuthority(string? certPem, string? keyPem)
    {
        if (string.IsNullOrWhiteSpace(certPem) || string.IsNullOrWhiteSpace(keyPem))
            throw new InvalidOperationException($"{CertVariable} and {KeyVariable} are required (PEM of the Chameleon CA)");
        try
        {
            _ca = X509Certificate2.CreateFromPem(certPem, keyPem);
        }
        catch (CryptographicException ex)
        {
            throw new InvalidOperationException($"{CertVariable}/{KeyVariable} are invalid: {ex.Message}", ex);
        }
        if (_ca.Extensions.OfType<X509BasicConstraintsExtension>().FirstOrDefault() is not { CertificateAuthority: true })
            throw new InvalidOperationException($"{CertVariable} is not a CA certificate");
        CertificatePem = _ca.ExportCertificatePem();
    }

    public string CertificatePem { get; }

    /// A new self-signed root (tests and the local development CA).
    public static (string CertPem, string KeyPem) CreateRoot(string name)
    {
        using var key = ECDsa.Create(ECCurve.NamedCurves.nistP256);
        var req = new CertificateRequest($"CN={name}", key, HashAlgorithmName.SHA256);
        req.CertificateExtensions.Add(new X509BasicConstraintsExtension(true, false, 0, true));
        req.CertificateExtensions.Add(new X509KeyUsageExtension(X509KeyUsageFlags.KeyCertSign | X509KeyUsageFlags.CrlSign, true));
        req.CertificateExtensions.Add(new X509SubjectKeyIdentifierExtension(req.PublicKey, false));
        using var cert = req.CreateSelfSigned(DateTimeOffset.UtcNow.AddMinutes(-5), DateTimeOffset.UtcNow.AddYears(10));
        return (cert.ExportCertificatePem(), key.ExportPkcs8PrivateKeyPem());
    }

    /// A client certificate and its key, generated by the Chameleon (Inter model).
    public (string CertPem, string KeyPem) IssueClient(string commonName)
    {
        using var key = ECDsa.Create(ECCurve.NamedCurves.nistP256);
        using var cert = Sign(new CertificateRequest($"CN={commonName}", key, HashAlgorithmName.SHA256), ClientAuth, ClientValidity);
        return (cert.ExportCertificatePem(), key.ExportPkcs8PrivateKeyPem());
    }

    /// Signs the app's own CSR (its private key never reaches the Chameleon). The subject is ours,
    /// only the public key comes from the request, whose signature is checked.
    public string SignRequest(string csrPem, string commonName)
    {
        CertificateRequest loaded;
        try
        {
            loaded = CertificateRequest.LoadSigningRequestPem(csrPem, HashAlgorithmName.SHA256);
        }
        catch (Exception ex) when (ex is CryptographicException or ArgumentException)
        {
            throw new InvalidCertificateRequestException("invalid certificate signing request (CSR): " + ex.Message);
        }
        using var cert = Sign(new CertificateRequest(new X500DistinguishedName($"CN={commonName}"), loaded.PublicKey, HashAlgorithmName.SHA256),
            ClientAuth, ClientValidity);
        return cert.ExportCertificatePem();
    }

    /// The local mTLS endpoint's server certificate, with the private key (Kestrel).
    public X509Certificate2 IssueServer(IReadOnlyCollection<string> hostnames)
    {
        using var key = ECDsa.Create(ECCurve.NamedCurves.nistP256);
        var req = new CertificateRequest($"CN={hostnames.First()}", key, HashAlgorithmName.SHA256);
        var san = new SubjectAlternativeNameBuilder();
        foreach (var host in hostnames)
        {
            if (System.Net.IPAddress.TryParse(host, out var ip)) san.AddIpAddress(ip);
            else san.AddDnsName(host);
        }
        req.CertificateExtensions.Add(san.Build());
        using var cert = Sign(req, ServerAuth, TimeSpan.FromDays(365));
        return Usable(cert.CopyWithPrivateKey(key));
    }

    /// The certificate a connector presents on its webhooks (one per connector, like the real provider).
    public X509Certificate2 WebhookClient(string connector) => _webhook.GetOrAdd(connector, name =>
    {
        using var key = ECDsa.Create(ECCurve.NamedCurves.nistP256);
        using var cert = Sign(new CertificateRequest($"CN={name}.webhook.chameleon", key, HashAlgorithmName.SHA256), ClientAuth, ClientValidity);
        return Usable(cert.CopyWithPrivateKey(key));
    });

    /// True when the certificate chains to this CA (no revocation: certificates are matched by
    /// thumbprint against the subscription afterwards).
    public bool Issued(X509Certificate2 certificate)
    {
        using var chain = new X509Chain();
        chain.ChainPolicy.TrustMode = X509ChainTrustMode.CustomRootTrust;
        chain.ChainPolicy.CustomTrustStore.Add(_ca);
        chain.ChainPolicy.RevocationMode = X509RevocationMode.NoCheck;
        return chain.Build(certificate);
    }

    public static string Thumbprint(X509Certificate2 certificate) =>
        Convert.ToHexString(certificate.GetCertHash(HashAlgorithmName.SHA256));

    private X509Certificate2 Sign(CertificateRequest req, Oid usage, TimeSpan validity)
    {
        req.CertificateExtensions.Add(new X509BasicConstraintsExtension(false, false, 0, true));
        req.CertificateExtensions.Add(new X509KeyUsageExtension(X509KeyUsageFlags.DigitalSignature, true));
        req.CertificateExtensions.Add(new X509EnhancedKeyUsageExtension([usage], false));
        req.CertificateExtensions.Add(X509AuthorityKeyIdentifierExtension.CreateFromCertificate(_ca, true, false));

        var notBefore = DateTimeOffset.UtcNow.AddMinutes(-5);
        var notAfter = DateTimeOffset.UtcNow.Add(validity);
        if (notAfter > _ca.NotAfter) notAfter = _ca.NotAfter;
        var generator = _ca.GetECDsaPrivateKey() is { } ec
            ? X509SignatureGenerator.CreateForECDsa(ec)
            : X509SignatureGenerator.CreateForRSA(_ca.GetRSAPrivateKey()!, RSASignaturePadding.Pkcs1);
        var serial = RandomNumberGenerator.GetBytes(16);
        serial[0] &= 0x7F; // positive serial (RFC 5280)
        return req.Create(_ca.SubjectName, generator, notBefore, notAfter, serial);
    }

    // An ephemeral key cannot back a TLS handshake on Windows; a PKCS#12 round trip makes it usable.
    private static X509Certificate2 Usable(X509Certificate2 withKey)
    {
        using (withKey)
            return new X509Certificate2(withKey.Export(X509ContentType.Pkcs12));
    }
}

public sealed class InvalidCertificateRequestException(string message) : Exception(message);
